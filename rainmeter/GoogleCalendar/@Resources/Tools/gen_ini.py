field('FieldEnd', 'LblEnd', '#TxtLabelEnd#', COL2_X, PY + 220, HALF_W, 'Panel | PForm | PFormTime', lua("Edit('end')"))
field('FieldCal', 'LblCal', '#TxtCalendarHint#', IX, PY + 276, INNER_W, 'Panel | PForm', lua('CycleTarget()'))
w(f"[FieldCalDot]\nMeter=Shape\nX=(#Width#-46)\nY={PY + 286}\nShape=Ellipse 5,5,5 | StrokeWidth 0\nHidden=1\nGroup=Panel | PForm\n"
  f"LeftMouseUpAction={lua('CycleTarget()')}\n\n")
